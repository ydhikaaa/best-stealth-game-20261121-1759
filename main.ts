// main.ts — the hand-in program for Midnight Manifest.
// Copies game/ and screenshots/ from beside this file into the output
// directory (MAKEFUN_OUTPUT_DIR, or /output under the grader) and writes
// dossier.json there with buildDossier from the vendored kit library.
// Paths resolve relative to this file, never to the working directory.

import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(out, { recursive: true });
cpSync(join(here, 'game'), join(out, 'game'), { recursive: true });
cpSync(join(here, 'screenshots'), join(out, 'screenshots'), { recursive: true });

const dossier = buildDossier(out, {
  text_max_bytes: 163840,
  screenshots: { max: 4, max_bytes: 262144 },
  game_max_files: 993,
  game_max_bytes: 50331648,
  game_path_max_bytes: 1000,
});
writeFileSync(join(out, 'dossier.json'), dossier);
console.log(`Midnight Manifest handed in: ${dossier.length} dossier bytes -> ${out}`);
